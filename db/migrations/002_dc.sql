-- 002_dc.sql – Lược đồ CSDL kho dc1, dc2, dc3 (máy B).
-- Nguồn: docs/db.md mục 2.1–2.3 (bản sao), 2.7–2.11, 3.3, 3.5; docs/spec.md F3.
-- Chạy: psql -d dc1 -v dc_id=1 -f 002_dc.sql   (dc2: dc_id=2, dc3: dc_id=3)
-- Ghi chú: mật khẩu role không đặt ở đây (spec chưa quy định); hạ tầng đặt bằng ALTER ROLE.
-- SUBSCRIPTION sub_master cần HOST_A_IP nên không nằm trong file này.

\set ON_ERROR_STOP on

-- Thiếu hoặc sai dc_id thì báo lỗi; ON_ERROR_STOP làm psql thoát với mã khác 0.
\if :{?dc_id}
\else
    DO $$ BEGIN RAISE EXCEPTION 'Thieu bien dc_id. Chay: psql -v dc_id=N -f 002_dc.sql'; END $$;
\endif

SELECT (:dc_id IN (1, 2, 3)) AS dc_id_ok \gset
\if :dc_id_ok
\else
    DO $$ BEGIN RAISE EXCEPTION 'dc_id phai la 1, 2 hoac 3'; END $$;
\endif

BEGIN;

-- ---------------------------------------------------------------------------
-- Bản sao danh mục (db.md 2.1–2.3): cùng cột như HQ, khóa chính không IDENTITY.
-- Dữ liệu chép từ HQ qua SUBSCRIPTION sub_master.
-- ---------------------------------------------------------------------------

CREATE TABLE dc (
    dc_id       SMALLINT     PRIMARY KEY,
    dc_code     VARCHAR(10)  NOT NULL UNIQUE,
    dc_name     VARCHAR(100) NOT NULL,
    region      VARCHAR(10)  NOT NULL CHECK (region IN ('BAC', 'TRUNG', 'NAM')),
    address     VARCHAR(255),
    fdw_server  VARCHAR(50)  UNIQUE,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE product_category (
    category_id    INTEGER      PRIMARY KEY,
    category_code  VARCHAR(20)  NOT NULL UNIQUE,
    category_name  VARCHAR(100) NOT NULL,
    parent_id      INTEGER      NULL REFERENCES product_category (category_id)
);

CREATE TABLE product (
    product_id    BIGINT        PRIMARY KEY,
    sku           VARCHAR(30)   NOT NULL UNIQUE,
    product_name  VARCHAR(200)  NOT NULL,
    category_id   INTEGER       NOT NULL REFERENCES product_category (category_id),
    unit          VARCHAR(20)   NOT NULL,
    weight_kg     NUMERIC(10,3) CHECK (weight_kg >= 0),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- inventory (db.md 2.7): mảnh dc_id = :dc_id, version tăng bằng trigger.
-- ---------------------------------------------------------------------------

CREATE TABLE inventory (
    dc_id         SMALLINT    NOT NULL REFERENCES dc (dc_id) CHECK (dc_id = :dc_id),
    product_id    BIGINT      NOT NULL REFERENCES product (product_id),
    qty_on_hand   INTEGER     NOT NULL DEFAULT 0 CHECK (qty_on_hand >= 0),
    qty_reserved  INTEGER     NOT NULL DEFAULT 0
                  CHECK (qty_reserved BETWEEN 0 AND qty_on_hand),
    version       BIGINT      NOT NULL DEFAULT 1,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (dc_id, product_id)
);

CREATE FUNCTION bump_version() RETURNS trigger AS $$
BEGIN
    NEW.version := OLD.version + 1;
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_inventory_version
    BEFORE UPDATE ON inventory
    FOR EACH ROW EXECUTE FUNCTION bump_version();

-- ---------------------------------------------------------------------------
-- stock_movement (db.md 2.8): sổ chỉ ghi thêm. CHECK mảnh theo db.md 3.5.
-- ---------------------------------------------------------------------------

CREATE TABLE stock_movement (
    movement_id    BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id     UUID        NOT NULL UNIQUE,
    dc_id          SMALLINT    NOT NULL CHECK (dc_id = :dc_id),
    product_id     BIGINT      NOT NULL,
    movement_type  VARCHAR(15) NOT NULL
                   CHECK (movement_type IN
                          ('INBOUND', 'OUTBOUND', 'TRANSFER_OUT', 'TRANSFER_IN', 'ADJUST')),
    qty_change     INTEGER     NOT NULL CHECK (qty_change <> 0),
    ref_type       VARCHAR(20) NOT NULL
                   CHECK (ref_type IN
                          ('ISSUE', 'RECEIPT', 'TRANSFER', 'REPLAY', 'STOCKTAKE', 'DIRECT')),
    ref_id         VARCHAR(64),
    created_by     VARCHAR(50),
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    FOREIGN KEY (dc_id, product_id) REFERENCES inventory (dc_id, product_id)
);

-- ---------------------------------------------------------------------------
-- transfer_order (db.md 2.9): mảnh theo direction.
-- ---------------------------------------------------------------------------

CREATE TABLE transfer_order (
    transfer_id    UUID        PRIMARY KEY,
    transfer_code  VARCHAR(20) NOT NULL UNIQUE,
    from_dc_id     SMALLINT    NOT NULL REFERENCES dc (dc_id),
    to_dc_id       SMALLINT    NOT NULL REFERENCES dc (dc_id),
    direction      VARCHAR(8)  NOT NULL CHECK (direction IN ('OUTBOUND', 'INBOUND')),
    status         VARCHAR(15) NOT NULL DEFAULT 'CREATED'
                   CHECK (status IN ('CREATED', 'SHIPPED', 'RECEIVED', 'CANCELLED')),
    cancel_reason  VARCHAR(30)
                   CHECK (cancel_reason IN ('DECLINED', 'INSUFFICIENT_STOCK', 'TIMEOUT')),
    note           TEXT,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    shipped_at     TIMESTAMPTZ,
    received_at    TIMESTAMPTZ,
    CHECK (to_dc_id <> from_dc_id),
    CHECK (
        (direction = 'OUTBOUND' AND from_dc_id = :dc_id) OR
        (direction = 'INBOUND'  AND to_dc_id   = :dc_id)
    )
);

-- ---------------------------------------------------------------------------
-- transfer_item (db.md 2.10): phân mảnh dẫn xuất theo transfer_order.
-- ---------------------------------------------------------------------------

CREATE TABLE transfer_item (
    transfer_id    UUID     NOT NULL REFERENCES transfer_order (transfer_id) ON DELETE CASCADE,
    line_no        SMALLINT NOT NULL,
    product_id     BIGINT   NOT NULL REFERENCES product (product_id),
    qty_requested  INTEGER  NOT NULL CHECK (qty_requested > 0),
    qty_shipped    INTEGER  CHECK (qty_shipped IS NULL OR qty_shipped = qty_requested),
    qty_received   INTEGER  CHECK (qty_received IS NULL OR qty_received = qty_requested),
    PRIMARY KEY (transfer_id, line_no),
    UNIQUE (transfer_id, product_id)
);

-- ---------------------------------------------------------------------------
-- outbox_event (db.md 2.11)
-- ---------------------------------------------------------------------------

CREATE TABLE outbox_event (
    event_id        UUID        PRIMARY KEY,
    aggregate_type  VARCHAR(30) NOT NULL CHECK (aggregate_type IN ('INVENTORY', 'TRANSFER')),
    aggregate_id    VARCHAR(64) NOT NULL,
    event_type      VARCHAR(50) NOT NULL
                    CHECK (event_type IN
                           ('InventoryChanged', 'InventoryChangedDirect', 'TransferCreated',
                            'TransferShipped', 'TransferReceived', 'TransferCancelled')),
    payload         JSONB       NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Role và quyền (F3; db.md 2.3, 2.8, 3.3)
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'node_app') THEN
        CREATE ROLE node_app LOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'debezium') THEN
        CREATE ROLE debezium LOGIN REPLICATION;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'fdw_reader') THEN
        CREATE ROLE fdw_reader LOGIN;
    END IF;
END
$$;

-- Bản sao danh mục: chỉ đọc với mọi role ứng dụng.
REVOKE INSERT, UPDATE, DELETE, TRUNCATE ON dc, product_category, product FROM PUBLIC;
GRANT SELECT ON dc, product_category, product TO node_app;

-- node_app
GRANT SELECT, INSERT, UPDATE ON inventory, transfer_order, transfer_item TO node_app;
GRANT SELECT, INSERT ON stock_movement, outbox_event TO node_app;
-- INSERT vào stock_movement cần dùng sequence IDENTITY của movement_id.
GRANT USAGE ON SEQUENCE stock_movement_movement_id_seq TO node_app;

-- debezium
GRANT SELECT ON outbox_event TO debezium;

-- fdw_reader
GRANT SELECT ON inventory, stock_movement, transfer_order, transfer_item TO fdw_reader;

-- Thu hồi DELETE trên inventory với mọi role (db.md 3.3 lớp 2).
REVOKE DELETE ON inventory FROM PUBLIC, node_app, debezium, fdw_reader;

COMMIT;
