-- 001_hq.sql – Lược đồ hq_db (máy A).
-- Nguồn: docs/db.md mục 1, 2.1–2.6, 2.12–2.14, 3.1; docs/spec.md F3.
-- Chạy: psql -d hq_db -f 001_hq.sql
-- Ghi chú: mật khẩu role không đặt ở đây (spec chưa quy định); hạ tầng đặt bằng ALTER ROLE.

\set ON_ERROR_STOP on

BEGIN;

-- ---------------------------------------------------------------------------
-- Danh mục gốc (db.md 2.1–2.3)
-- ---------------------------------------------------------------------------

CREATE TABLE dc (
    dc_id       SMALLINT     PRIMARY KEY,
    dc_code     VARCHAR(10)  NOT NULL UNIQUE,
    dc_name     VARCHAR(100) NOT NULL,
    region      VARCHAR(10)  NOT NULL CHECK (region IN ('BAC', 'TRUNG', 'NAM')),
    address     VARCHAR(255),
    fdw_server  VARCHAR(50)  UNIQUE,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE product_category (
    category_id    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code  VARCHAR(20)  NOT NULL UNIQUE,
    category_name  VARCHAR(100) NOT NULL,
    parent_id      INTEGER      NULL REFERENCES product_category (category_id)
);

CREATE TABLE product (
    product_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku           VARCHAR(30)   NOT NULL UNIQUE,
    product_name  VARCHAR(200)  NOT NULL,
    category_id   INTEGER       NOT NULL REFERENCES product_category (category_id),
    unit          VARCHAR(20)   NOT NULL,
    weight_kg     NUMERIC(10,3) CHECK (weight_kg >= 0),
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- inventory_snapshot (db.md 2.4)
-- ---------------------------------------------------------------------------

CREATE TABLE inventory_snapshot (
    dc_id          SMALLINT    NOT NULL REFERENCES dc (dc_id),
    product_id     BIGINT      NOT NULL REFERENCES product (product_id),
    qty_on_hand    INTEGER     NOT NULL DEFAULT 0 CHECK (qty_on_hand >= 0),
    qty_reserved   INTEGER     NOT NULL DEFAULT 0 CHECK (qty_reserved >= 0),
    last_version   BIGINT      NOT NULL DEFAULT 0,
    last_event_id  UUID,
    synced_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (dc_id, product_id)
);

-- ---------------------------------------------------------------------------
-- transfer_summary (db.md 2.5) và sequence mã phiếu (db.md 3.1)
-- ---------------------------------------------------------------------------

CREATE SEQUENCE transfer_code_seq;

CREATE TABLE transfer_summary (
    transfer_id    UUID        PRIMARY KEY,
    transfer_code  VARCHAR(20) NOT NULL UNIQUE,
    from_dc_id     SMALLINT    NOT NULL REFERENCES dc (dc_id),
    to_dc_id       SMALLINT    NOT NULL REFERENCES dc (dc_id),
    status         VARCHAR(15) NOT NULL
                   CHECK (status IN ('CREATED', 'SHIPPED', 'RECEIVED', 'CANCELLED')),
    total_lines    INTEGER     CHECK (total_lines >= 0),
    total_qty      INTEGER     CHECK (total_qty >= 0),
    items          JSONB       NOT NULL,
    cancel_reason  VARCHAR(30)
                   CHECK (cancel_reason IN ('DECLINED', 'INSUFFICIENT_STOCK', 'TIMEOUT')),
    cancelled_at   TIMESTAMPTZ,
    last_sync_at   TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL,
    shipped_at     TIMESTAMPTZ,
    received_at    TIMESTAMPTZ,
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (to_dc_id <> from_dc_id)
);

-- Hàng đang đi đường (db.md 2.4)
CREATE VIEW v_in_transit AS
SELECT s.to_dc_id                     AS dc_id,
       (i->>'product_id')::BIGINT     AS product_id,
       SUM((i->>'qty')::INT)          AS qty_in_transit
FROM transfer_summary s
CROSS JOIN LATERAL jsonb_array_elements(s.items) AS i
WHERE s.status = 'SHIPPED'
GROUP BY s.to_dc_id, (i->>'product_id')::BIGINT;

-- ---------------------------------------------------------------------------
-- processed_event (db.md 2.6)
-- ---------------------------------------------------------------------------

CREATE TABLE processed_event (
    event_id      UUID        PRIMARY KEY,
    source_dc     SMALLINT    NOT NULL,
    event_type    VARCHAR(50) NOT NULL,
    aggregate_id  VARCHAR(64) NOT NULL,
    processed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- pending_txn (db.md 2.12)
-- ---------------------------------------------------------------------------

CREATE TABLE pending_txn (
    txn_id      UUID        PRIMARY KEY,
    dc_id       SMALLINT    NOT NULL REFERENCES dc (dc_id),
    txn_type    VARCHAR(10) NOT NULL CHECK (txn_type IN ('INBOUND', 'OUTBOUND')),
    product_id  BIGINT      NOT NULL REFERENCES product (product_id),
    qty         INTEGER     NOT NULL CHECK (qty > 0),
    status      VARCHAR(10) NOT NULL DEFAULT 'PENDING'
                CHECK (status IN ('PENDING', 'APPLIED', 'REJECTED')),
    created_by  VARCHAR(50),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ,
    attempts    SMALLINT    NOT NULL DEFAULT 0,
    applied_at  TIMESTAMPTZ,
    error_msg   TEXT
);

CREATE INDEX ON pending_txn (dc_id, status, created_at);

-- ---------------------------------------------------------------------------
-- transfer_event (db.md 2.13)
-- ---------------------------------------------------------------------------

CREATE TABLE transfer_event (
    event_id     UUID        PRIMARY KEY,
    transfer_id  UUID        NOT NULL REFERENCES transfer_summary (transfer_id),
    from_status  VARCHAR(15),
    to_status    VARCHAR(15) NOT NULL
                 CHECK (to_status IN ('CREATED', 'SHIPPED', 'RECEIVED', 'CANCELLED')),
    source       VARCHAR(10) NOT NULL CHECK (source IN ('HQ', 'DC1', 'DC2', 'DC3')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- dc_status (db.md 2.14)
-- ---------------------------------------------------------------------------

CREATE TABLE dc_status (
    dc_id              SMALLINT    PRIMARY KEY REFERENCES dc (dc_id),
    status             VARCHAR(10) NOT NULL DEFAULT 'RECOVERING'
                       CHECK (status IN ('ONLINE', 'OFFLINE', 'RECOVERING')),
    node_mode          VARCHAR(10) CHECK (node_mode IN ('ONLINE', 'RECOVERING')),
    last_heartbeat_at  TIMESTAMPTZ,
    missed_count       SMALLINT    NOT NULL DEFAULT 0,
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ---------------------------------------------------------------------------
-- Logical replication danh mục (F3)
-- ---------------------------------------------------------------------------

CREATE PUBLICATION pub_master FOR TABLE dc, product_category, product;

-- ---------------------------------------------------------------------------
-- Role và quyền (F3)
-- ---------------------------------------------------------------------------

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'hq_app') THEN
        CREATE ROLE hq_app LOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'repl_sub') THEN
        CREATE ROLE repl_sub LOGIN REPLICATION;
    END IF;
END
$$;

-- hq_app: HQ API và Consumer đọc/ghi bảng HQ, dùng transfer_code_seq.
GRANT SELECT, INSERT, UPDATE ON
    dc, product_category, product,
    inventory_snapshot, transfer_summary, processed_event,
    pending_txn, transfer_event, dc_status
TO hq_app;
GRANT SELECT ON v_in_transit TO hq_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO hq_app;

-- repl_sub: subscription của 3 kho chỉ đọc 3 bảng danh mục.
GRANT SELECT ON dc, product_category, product TO repl_sub;

COMMIT;
